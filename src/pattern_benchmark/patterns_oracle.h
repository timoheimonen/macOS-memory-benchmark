/** Exact O(1) full-cycle XOR across all 32B slots in `[offset, offset+span)`. */
uint64_t compute_patterns_strided_full_cycle_xor(
    const PatternsPatternTable& table, size_t offset_bytes, size_t span_bytes) noexcept;

/** Exact O(1) 2D partial-cycle XOR across `rem_phases` passes starting at phase 0. */
uint64_t compute_patterns_strided_partial_cycle_xor(
    const PatternsPatternTable& table, size_t offset_bytes, size_t span_bytes,
    size_t stride_bytes, size_t rem_phases) noexcept;

/** Exact `pass_xor` across a worker's 32B-aligned random byte offsets. */
