/** Precomputed GF(2) tables for `patterns-buffer-pattern-v1`. */
struct PatternsPatternTable {
  std::array<uint64_t, 256> table{};
  std::array<uint64_t, 257> prefix_t{};
  std::array<uint64_t, 64> s_t{};
  std::array<uint64_t, 65> prefix_st{};
  std::array<uint64_t, 33> prefix_st_even{};
  std::array<uint64_t, 33> prefix_st_odd{};
};

/** Per-worker generated byte offsets for the `random` pattern. */
struct PatternsRandomWorkerIndices {
  size_t offset_bytes = 0;
  size_t span_bytes = 0;
  std::vector<size_t> indices;  ///< Relative 32B-aligned byte offsets in [0, span_bytes - 32]
};

/** Complete `random` workload generated once per run via `splitmix64-coprime-fisher-yates-v1`. */
struct PatternsRandomWorkload {
  uint64_t random_seed = 0;
  size_t selected_accesses_per_pass = 0;
  size_t distinct_address_count = 0;
  size_t logical_working_set_bytes = 0;
  std::string random_indices_sha256;
  std::vector<PatternsRandomWorkerIndices> workers;
  std::vector<std::vector<size_t>> sorted_validation_indices;  ///< Per-worker ascending copy (<= 8 MiB total)
  std::vector<uint64_t> worker_pass_xors;  ///< Precomputed once per run
};

/** Separate validation status for touched bytes and untouched sentinel bytes. */
struct PatternsPostValidationResult {
  bool touched_ok = false;
  bool untouched_ok = true;
};

/** 64-bit left circular rotation. */
inline uint64_t patterns_rotl64(uint64_t value, unsigned int shift) noexcept {
  shift &= 63U;
  if (shift == 0U) {
    return value;
  }
  return (value << shift) | (value >> (64U - shift));
}

/** Lane index GF(2) mixing polynomial. */
inline uint64_t patterns_lane_mix(uint64_t word_index) noexcept {
  return word_index ^ patterns_rotl64(word_index, 7U) ^
         patterns_rotl64(word_index, 33U);
}

/** 32-byte slot index GF(2) mixing polynomial. */
inline uint64_t patterns_slot_mix(uint64_t slot_index) noexcept {
  return slot_index ^ patterns_rotl64(slot_index, 19U) ^
         patterns_rotl64(slot_index, 41U);
}

/** Build `T[0..255]`, `S_T[0..63]`, and prefix XOR tables for `src_seed`. */
PatternsPatternTable build_patterns_pattern_table(uint64_t src_seed) noexcept;

/** Compute 64-bit little-endian word `W[word_index]` for `patterns-buffer-pattern-v1`. */
inline uint64_t patterns_buffer_word(
    const PatternsPatternTable& table, uint64_t word_index) noexcept {
  const uint64_t slot = word_index >> 2U;
  const uint64_t slot_tag =
      ((word_index & 3ULL) == 0ULL) ? patterns_slot_mix(slot) : 0ULL;
  return table.table[word_index & 255ULL] ^ patterns_lane_mix(word_index) ^
         slot_tag;
}

/** Compute exact 4-word XOR of 32B-aligned slot `slot_index`. */
inline uint64_t patterns_slot_xor(
    const PatternsPatternTable& table, uint64_t slot_index) noexcept {
  return table.s_t[slot_index & 63ULL] ^ patterns_slot_mix(slot_index);
}

/** Initialize `src[0..bytes)` deterministically using `patterns-buffer-pattern-v1`. */
